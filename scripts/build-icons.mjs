const inner = (weight, name) => {
    const suffix = weight === 'regular' ? '' : `-${weight}`;
    const svg = readFileSync(join(assets, weight, `${name}${suffix}.svg`), 'utf8');
    const body = svg.replace(/^[\s\S]*?<svg[^>]*>/, '').replace(/<\/svg>\s*$/, '');
    if (!body.trim()) {
        throw new Error(`Empty glyph: ${weight}/${name}`);
    }
    return body.replace(/'/g, "\\'");
};

const lines = Object.keys(map).sort().map((key) => {
    const name = map[key];
    return `    '${key}' => ['${inner('regular', name)}', '${inner('fill', name)}'],`;
});

mkdirSync(dirname(out), { recursive: true });
writeFileSync(out, `<?php

/*
| Generated by scripts/build-icons.mjs from @phosphor-icons/core (MIT).
| Do not edit by hand: change the map in the script and run \`npm run icons\`.
|
| name => [regular, fill], each the inner markup of a 256x256 SVG.
*/

return [
${lines.join('\n')}
];
`);

console.log(`Wrote ${lines.length} icons to resources/icons/phosphor.php`);
